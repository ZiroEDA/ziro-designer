/**
 * The `ziroeda` message domain: ZiroEDA's own interface text, the messages
 * KiCad's catalogs do not have (the cloud, accounts, sharing, the launcher,
 * the browser's own dialogs).
 *
 *     node tools/translation/extract_ziroeda.mjs
 *
 * What `xgettext` and `msgmerge` do for KiCad's `kicad` domain
 * (translation/CMakeLists.txt and its update scripts), for ours:
 *
 *   1. every literal marked `_()`, `_HKI()`, `wxGetTranslation()` or
 *      `wxPLURAL()` in the source, that no KiCad catalog has, is a message;
 *   2. they are written to `translation/ziroeda/ziroeda.pot`, each with the
 *      places it comes from;
 *   3. each `translation/ziroeda/pofiles/<lang>.po` named in LINGUAS is
 *      brought up to the template: a message that is still there keeps its
 *      translation, a new one arrives untranslated, a gone one is dropped.
 *
 * Then `build_catalogs.mjs --ziroeda` compiles the `.po` files to
 * `translation/ziroeda/<lang>.json`, which the app loads beside KiCad's.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { parsePo } from './po_compile.mjs';

const repo = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(join(repo, 'package.json'));
const ts = require('typescript');

/** The folders whose source is the app (tests and generated tables are not). */
const SOURCES = [
  'common',
  'eeschema',
  'pcbnew',
  'gerbview',
  'pagelayout_editor',
  'pcb_calculator',
  'bitmap2component',
  'cvpcb',
  '3d-viewer',
  'designer/src',
  'external/wx',
  'ai',
  'include',
];
const MARKS = new Set(['_', '_HKI', 'wxGetTranslation', 'wxPLURAL']);

/** `wxStripMenuCodes`: "&Save" -> "Save", "Save (&S)" -> "Save" (external/wx/translation.ts). */
function stripMenuCodes(aStr) {
  let str = aStr;
  const pos = str.indexOf('(&');
  if (pos !== -1 && str.length > pos + 3 && str[pos + 3] === ')') {
    const start = pos > 0 && str[pos - 1] === ' ' ? pos - 1 : pos;
    str = str.slice(0, start) + str.slice(pos + 4);
  }
  let out = '';
  for (let i = 0; i < str.length; i++) {
    if (str[i] === '&' && i + 1 < str.length) i++;
    out += str[i];
  }
  return out;
}

/**
 * Every msgid KiCad's catalogs hold, and the mnemonic-free spelling of each - the catalog
 * answers to both - so those belong to the `kicad` domain.
 */
export function kicadMsgids(aTranslationDir) {
  const ids = new Set();
  for (const f of readdirSync(aTranslationDir)) {
    if (!f.endsWith('.json')) continue;
    const data = JSON.parse(readFileSync(join(aTranslationDir, f), 'utf8'));
    for (const k of Object.keys(data.messages)) {
      ids.add(k);
      if (k.includes('&')) ids.add(stripMenuCodes(k));
    }
  }
  return ids;
}

/**
 * The marked literals of one source text: [{ msgid, plural?, line }]. A
 * template literal with substitutions is not a message (it was formatted
 * before the lookup) and is not taken.
 */
export function markedLiterals(aFileName, aSource) {
  const sf = ts.createSourceFile(
    aFileName,
    aSource,
    ts.ScriptTarget.Latest,
    true,
    aFileName.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );
  const out = [];
  const text = (n) =>
    n && (ts.isStringLiteral(n) || ts.isNoSubstitutionTemplateLiteral(n)) ? n.text : null;
  const visit = (n) => {
    if (ts.isCallExpression(n) && ts.isIdentifier(n.expression) && MARKS.has(n.expression.text)) {
      const msgid = text(n.arguments[0]);
      if (msgid !== null && msgid !== '') {
        const line = sf.getLineAndCharacterOfPosition(n.getStart(sf)).line + 1;
        const plural = n.expression.text === 'wxPLURAL' ? text(n.arguments[1]) : null;
        out.push(plural ? { msgid, plural, line } : { msgid, line });
      }
    }
    ts.forEachChild(n, visit);
  };
  visit(sf);
  return out;
}

/** A PO string literal: `"..."` with C escapes, split at newlines the way xgettext does. */
export function poString(aKeyword, aText) {
  const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\t/g, '\\t');
  if (!aText.includes('\n') || aText.indexOf('\n') === aText.length - 1)
    return `${aKeyword} "${esc(aText).replace(/\n/g, '\\n')}"`;
  const pieces = aText.split(/(?<=\n)/).map((p) => `"${esc(p).replace(/\n/g, '\\n')}"`);
  return `${aKeyword} ""\n${pieces.join('\n')}`;
}

/** The template: the header and every message with its references. */
export function buildPot(aMessages) {
  const head = [
    "# ZiroEDA's own interface text: the `ziroeda` message domain.",
    '# Generated by tools/translation/extract_ziroeda.mjs - do not edit; edit the .po files.',
    'msgid ""',
    'msgstr ""',
    '"Project-Id-Version: ZiroEDA\\n"',
    '"MIME-Version: 1.0\\n"',
    '"Content-Type: text/plain; charset=UTF-8\\n"',
    '"Content-Transfer-Encoding: 8bit\\n"',
    '',
  ];
  const body = [];
  for (const [msgid, m] of aMessages) {
    body.push(`#: ${[...m.refs].slice(0, 6).join(' ')}`);
    body.push(poString('msgid', msgid));
    if (m.plural) {
      body.push(poString('msgid_plural', m.plural));
      body.push('msgstr[0] ""', 'msgstr[1] ""');
    } else {
      body.push('msgstr ""');
    }
    body.push('');
  }
  return `${head.join('\n')}\n${body.join('\n')}`;
}

/**
 * One language's `.po` brought up to the template (msgmerge): its header
 * kept, every template message with the translation it had, if any.
 */
export function mergePo(aExisting, aMessages, aLang, aPluralForms) {
  const old = new Map();
  let header = null;
  if (aExisting) {
    for (const e of parsePo(aExisting)) {
      if (e.msgid === '' && e.msgctxt === null) header = e.msgstr[0];
      else if (e.msgctxt === null) old.set(e.msgid, e);
    }
  }
  const hdr =
    header ??
    [
      'Project-Id-Version: ZiroEDA\n',
      `Language: ${aLang}\n`,
      'MIME-Version: 1.0\n',
      'Content-Type: text/plain; charset=UTF-8\n',
      'Content-Transfer-Encoding: 8bit\n',
      `Plural-Forms: ${aPluralForms}\n`,
    ].join('');
  const lines = [
    'msgid ""',
    poString('msgstr', hdr).replace(/^msgstr "(.*)"$/, 'msgstr ""\n"$1"'),
    '',
  ];
  for (const [msgid, m] of aMessages) {
    const prev = old.get(msgid);
    lines.push(`#: ${[...m.refs].slice(0, 6).join(' ')}`);
    if (prev?.fuzzy) lines.push('#, fuzzy');
    lines.push(poString('msgid', msgid));
    if (m.plural) {
      lines.push(poString('msgid_plural', m.plural));
      const forms = prev && prev.msgidPlural !== null ? prev.msgstr : [];
      const n = Math.max(2, forms.length);
      for (let i = 0; i < n; i++) lines.push(poString(`msgstr[${i}]`, forms[i] ?? ''));
    } else {
      lines.push(
        poString('msgstr', prev && prev.msgidPlural === null ? (prev.msgstr[0] ?? '') : ''),
      );
    }
    lines.push('');
  }
  return `${lines.join('\n')}`;
}

function main() {
  const kicad = kicadMsgids(join(repo, 'translation'));
  const messages = new Map();
  // The KiCad messages the app shows, as the source spells them: where one language's KiCad
  // catalog has no translation, that language's .po fills the gap (see below).
  const kicadUsed = new Map();
  for (const dir of SOURCES) {
    if (!existsSync(join(repo, dir))) continue;
    const files = execFileSync('git', ['ls-files', '-co', '--exclude-standard', dir], { cwd: repo })
      .toString()
      .split('\n')
      .filter((f) => /\.tsx?$/.test(f) && !/\.test\.tsx?$/.test(f) && !/\.d\.ts$/.test(f));
    for (const file of files) {
      for (const m of markedLiterals(file, readFileSync(join(repo, file), 'utf8'))) {
        if (!/[A-Za-z]/.test(m.msgid)) continue;
        if (kicad.has(m.msgid)) {
          if (!kicadUsed.has(m.msgid))
            kicadUsed.set(m.msgid, { plural: m.plural ?? null, refs: new Set() });
          kicadUsed.get(m.msgid).refs.add(`${file}:${m.line}`);
          continue;
        }
        if (!messages.has(m.msgid))
          messages.set(m.msgid, { plural: m.plural ?? null, refs: new Set() });
        messages.get(m.msgid).refs.add(`${file}:${m.line}`);
      }
    }
  }
  const sorted = new Map([...messages].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
  const domain = join(repo, 'translation/ziroeda');
  const poDir = join(domain, 'pofiles');
  mkdirSync(poDir, { recursive: true });
  writeFileSync(join(domain, 'ziroeda.pot'), buildPot(sorted));

  // The languages are KiCad's: a ZiroEDA catalog exists for every language the interface offers.
  const kicadLinguas = readdirSync(join(repo, 'translation'))
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.slice(0, -5));
  const linguasPath = join(poDir, 'LINGUAS');
  if (!existsSync(linguasPath)) writeFileSync(linguasPath, `${kicadLinguas.join('\n')}\n`);
  const linguas = readFileSync(linguasPath, 'utf8')
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('#'));
  const gapCounts = [];
  for (const lang of linguas) {
    const path = join(poDir, `${lang}.po`);
    const kicadCatalog = JSON.parse(
      readFileSync(join(repo, 'translation', `${lang}.json`), 'utf8'),
    );
    const pluralForms = `nplurals=${kicadCatalog.nplurals}; plural=${kicadCatalog.plural};`;
    // KiCad's own catalog for this language is incomplete: a message it does not translate
    // (directly, or by its mnemonic-free spelling) is filled here. Loaded after KiCad's, ours
    // never overrides a translation KiCad has.
    const translated = new Set();
    for (const k of Object.keys(kicadCatalog.messages)) {
      translated.add(k);
      if (k.includes('&')) translated.add(stripMenuCodes(k));
    }
    // English is the msgid itself: it has nothing to fill.
    const gaps = lang === 'en' ? [] : [...kicadUsed].filter(([id]) => !translated.has(id));
    const forLang = new Map(
      [...sorted, ...gaps].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
    );
    gapCounts.push(`${lang} ${gaps.length}`);
    writeFileSync(
      path,
      mergePo(existsSync(path) ? readFileSync(path, 'utf8') : null, forLang, lang, pluralForms),
    );
  }
  console.log(`${sorted.size} ZiroEDA messages, ${linguas.length} languages`);
  console.log(`KiCad gaps filled per language: ${gapCounts.join(', ')}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
