function isBox(a: unknown): a is BOX2I {
  return (
    typeof (a as BOX2I).Inflate === 'function' && typeof (a as BOX2I).Intersects === 'function'
  );
}

function isPoint(a: unknown): a is VECTOR2I {
  return typeof (a as VECTOR2I).x === 'number' && !isBox(a);
}

