  SetTextAngle(aAngle: EDA_ANGLE): void {
    const delta = aAngle.Normalized().sub(this.GetTextAngle());

    this.Rotate(this.GetPosition(), delta);
  }

  GetDrawPos(aIsFlipped = false): VECTOR2I {
    const drawAngle = this.GetDrawRotation();
    const corners = this.GetCornersInSequence(drawAngle);
    let horizontalAlignment = this.GetHorizJustify();
    const verticalAlignment = this.GetVertJustify();
    let textAnchor: VECTOR2I = { x: 0, y: 0 };
    const offset: VECTOR2I = { x: 0, y: 0 };

    // Calculate midpoints
    const midTop = divideI(add(corners[0]!, corners[1]!), 2);
    const midBottom = divideI(add(corners[3]!, corners[2]!), 2);
    const midLeft = divideI(add(corners[0]!, corners[3]!), 2);
    const midRight = divideI(add(corners[1]!, corners[2]!), 2);
    const center = divideI(add(add(add(corners[0]!, corners[1]!), corners[2]!), corners[3]!), 4);

    if (this.IsMirrored() !== aIsFlipped) {
      switch (this.GetHorizJustify()) {
        case GR_TEXT_H_ALIGN_T.GR_TEXT_H_ALIGN_LEFT:
          horizontalAlignment = GR_TEXT_H_ALIGN_T.GR_TEXT_H_ALIGN_RIGHT;
          break;
        case GR_TEXT_H_ALIGN_T.GR_TEXT_H_ALIGN_CENTER:
          horizontalAlignment = GR_TEXT_H_ALIGN_T.GR_TEXT_H_ALIGN_CENTER;
          break;
        case GR_TEXT_H_ALIGN_T.GR_TEXT_H_ALIGN_RIGHT:
          horizontalAlignment = GR_TEXT_H_ALIGN_T.GR_TEXT_H_ALIGN_LEFT;
          break;
        case GR_TEXT_H_ALIGN_T.GR_TEXT_H_ALIGN_INDETERMINATE:
          horizontalAlignment = GR_TEXT_H_ALIGN_T.GR_TEXT_H_ALIGN_INDETERMINATE;
          break;
      }
    }

    console.assert(
      horizontalAlignment !== GR_TEXT_H_ALIGN_T.GR_TEXT_H_ALIGN_INDETERMINATE &&
        verticalAlignment !== GR_TEXT_V_ALIGN_T.GR_TEXT_V_ALIGN_INDETERMINATE,
      'Indeterminate state legal only in dialogs. Horizontal and vertical alignment ' +
        'must be set before calling PCB_TEXTBOX::GetDrawPos.',
    );

    if (
      horizontalAlignment === GR_TEXT_H_ALIGN_T.GR_TEXT_H_ALIGN_INDETERMINATE ||
      verticalAlignment === GR_TEXT_V_ALIGN_T.GR_TEXT_V_ALIGN_INDETERMINATE
    ) {
      return center;
    }

    const H = GR_TEXT_H_ALIGN_T;
    const V = GR_TEXT_V_ALIGN_T;

    if (
      horizontalAlignment === H.GR_TEXT_H_ALIGN_LEFT &&
      verticalAlignment === V.GR_TEXT_V_ALIGN_TOP
    ) {
      textAnchor = corners[0]!;
    } else if (
      horizontalAlignment === H.GR_TEXT_H_ALIGN_CENTER &&
      verticalAlignment === V.GR_TEXT_V_ALIGN_TOP
    ) {
      textAnchor = midTop;
    } else if (
      horizontalAlignment === H.GR_TEXT_H_ALIGN_RIGHT &&
      verticalAlignment === V.GR_TEXT_V_ALIGN_TOP
    ) {
      textAnchor = corners[1]!;
    } else if (
      horizontalAlignment === H.GR_TEXT_H_ALIGN_LEFT &&
      verticalAlignment === V.GR_TEXT_V_ALIGN_CENTER
    ) {
      textAnchor = midLeft;
    } else if (
      horizontalAlignment === H.GR_TEXT_H_ALIGN_CENTER &&
      verticalAlignment === V.GR_TEXT_V_ALIGN_CENTER
    ) {
      textAnchor = center;
    } else if (
      horizontalAlignment === H.GR_TEXT_H_ALIGN_RIGHT &&
      verticalAlignment === V.GR_TEXT_V_ALIGN_CENTER
    ) {
      textAnchor = midRight;
    } else if (
      horizontalAlignment === H.GR_TEXT_H_ALIGN_LEFT &&
      verticalAlignment === V.GR_TEXT_V_ALIGN_BOTTOM
    ) {
      textAnchor = corners[3]!;
    } else if (
      horizontalAlignment === H.GR_TEXT_H_ALIGN_CENTER &&
      verticalAlignment === V.GR_TEXT_V_ALIGN_BOTTOM
    ) {
      textAnchor = midBottom;
    } else if (
      horizontalAlignment === H.GR_TEXT_H_ALIGN_RIGHT &&
      verticalAlignment === V.GR_TEXT_V_ALIGN_BOTTOM
    ) {
      textAnchor = corners[2]!;
    }

    const marginLeft = this.GetMarginLeft();
    const marginRight = this.GetMarginRight();
    const marginTop = this.GetMarginTop();
    const marginBottom = this.GetMarginBottom();

    if (horizontalAlignment === H.GR_TEXT_H_ALIGN_LEFT) offset.x = marginLeft;
    else if (horizontalAlignment === H.GR_TEXT_H_ALIGN_RIGHT) offset.x = -marginRight;

    if (verticalAlignment === V.GR_TEXT_V_ALIGN_TOP) offset.y = marginTop;
    else if (verticalAlignment === V.GR_TEXT_V_ALIGN_BOTTOM) offset.y = -marginBottom;

    const rotated = RotatePoint(offset, this.GetDrawRotation());

    return add(textAnchor, rotated);
  }

  override ViewGetLOD(aLayer: number, aView: PCB_VIEW_FOR_LOD | null): number {
    const renderSettings = aView!.GetPainter().GetSettings();

    if (aLayer === GAL_LAYER_ID.LAYER_LOCKED_ITEM_SHADOW) {
      // Hide shadow if the main layer is not shown
      if (!aView!.IsLayerVisible(this.m_layer)) return PCB_TEXTBOX.LOD_HIDE;

      // Hide shadow on dimmed tracks
      if (renderSettings.GetHighContrast()) {
        if (this.m_layer !== renderSettings.GetPrimaryHighContrastLayer())
          return PCB_TEXTBOX.LOD_HIDE;
      }
    }

    return PCB_TEXTBOX.LOD_SHOW;
  }

  override ViewGetLayers(): number[] {
    if (this.IsLocked() || (this.GetParentFootprint() && this.GetParentFootprint()!.IsLocked()))
      return [this.GetLayer(), GAL_LAYER_ID.LAYER_LOCKED_ITEM_SHADOW];

    return [this.GetLayer()];
  }

  GetShownText(aAllowExtraText: boolean, aDepth = 0): string {
    const parentFootprint = this.GetParentFootprint();
    const board = this.GetBoard();

    const resolver: TextVarResolverFn = (token) => {
      if (token.value === 'LAYER') {
        token.value = this.GetLayerName();
        return true;
      }

      if (parentFootprint && parentFootprint.ResolveTextVar(token, aDepth + 1)) return true;

      if (board!.ResolveTextVar(token, aDepth + 1)) return true;

      return false;
    };

    let text = EDA_TEXT.prototype.GetShownText.call(this, aAllowExtraText, aDepth);

    if (this.HasTextVars()) text = ResolveTextVars(text, resolver, { value: aDepth });

    const font = this.GetDrawFont(null);
    const drawAngle = this.GetDrawRotation();
    const corners = this.GetCornersInSequence(drawAngle);
    let colWidth = EuclideanNormI(sub(corners[1]!, corners[0]!));

    if (this.GetTextAngle().IsHorizontal())
      colWidth -= this.GetMarginLeft() + this.GetMarginRight();
    else colWidth -= this.GetMarginTop() + this.GetMarginBottom();

    const wrapped: OutStr = { value: text };
    font.LinebreakText(
      wrapped,
      colWidth,
      this.GetTextSize(),
      this.GetTextThickness(),
      this.IsBold(),
      this.IsItalic(),
    );
    text = wrapped.value;

    // Convert escape markers back to literal ${} and @{} for final display
    text = text.replaceAll('<<<ESC_DOLLAR:', '${');
    text = text.replaceAll('<<<ESC_AT:', '@{');

    return text;
  }

