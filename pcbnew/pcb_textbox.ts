  override IsType(aScanTypes: readonly KICAD_T[]): boolean {
    if (BOARD_ITEM.prototype.IsType.call(this, aScanTypes)) return true;

    for (const scanType of aScanTypes) {
      if (scanType === KICAD_T.PCB_LOCATE_TEXT_T) return true;
    }

    return false;
  }

  override GetFriendlyName(): string {
    return 'Text Box';
  }

  override StyleFromSettings(settings: BOARD_DESIGN_SETTINGS, aCheckSide: boolean): void {
    PCB_SHAPE.prototype.StyleFromSettings.call(this, settings, aCheckSide);

    this.SetTextSize(settings.GetTextSize(this.GetLayer()));
    this.SetTextThickness(settings.GetTextThickness(this.GetLayer()));
    this.SetItalic(settings.GetTextItalic(this.GetLayer()));

    if (this.GetParentFootprint()) this.SetKeepUpright(settings.GetTextUpright(this.GetLayer()));

    if (aCheckSide) {
      const board = this.GetBoard();

      if (board) this.SetMirrored(board.IsBackLayer(this.GetLayer()));
      else this.SetMirrored(IsBackLayer(this.GetLayer()));
    }
  }

  GetLegacyTextMargin(): number {
    return KiROUND(this.GetStroke().GetWidth() / 2.0) + KiROUND(this.GetTextSize().y * 0.75);
  }

  /**
   * Return the minimum height needed to contain the textbox's wrapped text content
   * plus margins. Width is unconstrained (returns 0) so text freely rewraps.
   * The constrained axis depends on rotation: y-axis for 0/180, x-axis for 90/270.
   */
  GetMinSize(): VECTOR2I {
    if (this.GetText().length === 0) return { x: 0, y: 0 };

    const textBox = this.GetTextBox(null);
    let textHeight = Math.abs(textBox.GetHeight());

    if (this.GetTextAngle().IsHorizontal())
      textHeight += this.GetMarginTop() + this.GetMarginBottom();
    else textHeight += this.GetMarginLeft() + this.GetMarginRight();

    // Only enforce minimum height. Width returns 0 so the user can freely shrink width
    // (text rewraps) while height is constrained to fit the wrapped text content.
    // GetTextBox returns dimensions in text-local coordinates. For 90/270 degree rotations,
    // the text's natural height maps to screen x-axis.
    const rotation = this.GetDrawRotation();

    if (rotation.equals(ANGLE_90) || rotation.equals(ANGLE_270)) return { x: textHeight, y: 0 };

    return { x: 0, y: textHeight };
  }

  override GetTopLeft(): VECTOR2I {
    const rotation = this.GetDrawRotation();

    if (rotation.equals(ANGLE_90)) return { x: this.GetStartX(), y: this.GetEndY() };
    else if (rotation.equals(ANGLE_180)) return this.GetEnd();
    else if (rotation.equals(ANGLE_270)) return { x: this.GetEndX(), y: this.GetStartY() };
    else return this.GetStart();
  }

  override GetBotRight(): VECTOR2I {
    const rotation = this.GetDrawRotation();

    if (rotation.equals(ANGLE_90)) return { x: this.GetEndX(), y: this.GetStartY() };
    else if (rotation.equals(ANGLE_180)) return this.GetStart();
    else if (rotation.equals(ANGLE_270)) return { x: this.GetStartX(), y: this.GetEndY() };
    else return this.GetEnd();
  }

