  override Similarity(aBoardItem: BOARD_ITEM | EDA_SHAPE): number {
    if (!(aBoardItem instanceof BOARD_ITEM))
      return EDA_SHAPE.prototype.Similarity.call(this, aBoardItem);

    if (aBoardItem.Type() !== this.Type()) return 0.0;

    const other = aBoardItem as PCB_TEXTBOX;

    let similarity = 1.0;

    if (this.m_borderEnabled !== other.m_borderEnabled) similarity *= 0.9;

    if (this.GetMarginLeft() !== other.GetMarginLeft()) similarity *= 0.9;

    if (this.GetMarginTop() !== other.GetMarginTop()) similarity *= 0.9;

    if (this.GetMarginRight() !== other.GetMarginRight()) similarity *= 0.9;

    if (this.GetMarginBottom() !== other.GetMarginBottom()) similarity *= 0.9;

    similarity *= EDA_TEXT.prototype.Similarity.call(this, other as unknown as EDA_TEXT);

    return similarity;
  }

  /** `operator==( const BOARD_ITEM& )`. */
  override equals(aBoardItem: BOARD_ITEM): boolean {
    if (aBoardItem.Type() !== this.Type()) return false;

    const other = aBoardItem as PCB_TEXTBOX;

    return this.equalsTextbox(other);
  }

  /** `operator==( const PCB_TEXTBOX& )`. */
  equalsTextbox(aOther: PCB_TEXTBOX): boolean {
    return (
      this.m_borderEnabled === aOther.m_borderEnabled &&
      this.equalsEdaText(aOther as unknown as EDA_TEXT)
    );
  }

