/**
 * KiCad's own mouse cursors for the schematic tools, vendored from
 * `resources/bitmaps_png/cursors/*.xpm` (GPL, like the toolbar icons) and kept
 * in KiCad's XPM shape: a palette plus one string per pixel row. `cursors.ts`
 * paints them to a canvas and hands the browser a data-URI cursor.
 *
 * The hotspots are CURSOR_STORE's (common/gal/cursors.cpp).
 */

/** One cursor: 32x32 pixels, its palette, and KiCad's hotspot. */
export interface XpmCursor {
  /** Palette: XPM character -> CSS colour, '' for transparent. */
  palette: Record<string, string>;
  /** 32 rows of 32 palette characters. */
  rows: readonly string[];
  /** Hotspot (x, y) in pixels. */
  hotspot: readonly [number, number];
}

