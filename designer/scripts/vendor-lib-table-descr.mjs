/**
 * Vendor the global library tables' descriptions.
 *
 * The Description column against a LIBRARY row in either chooser is the
 * library TABLE row's `(descr …)`, not anything inside the library file:
 * `SYMBOL_TREE_MODEL_ADAPTER` reads `row->GetDescr()` and
 * `FP_TREE_MODEL_ADAPTER::AddLibraries` reads `m_libs->GetDescription( nickname )`.
 * KiCad ships those strings in `template/sym-lib-table` and
 * `template/fp-lib-table`, which become the user's global tables on first run.
 * The hosted indexes carry no such field, so the column was empty in both
 * choosers. This reads the two installed tables and writes them as data.
 *
 *   node designer/scripts/vendor-lib-table-descr.mjs [kicad template dir]
 *
 * Re-run rather than hand-editing the output; that is the whole point of
 * keeping it. [data] — KiCad's own table, mirrored, not invented.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const TEMPLATE = process.argv[2] ?? '/usr/share/kicad/template';
const OUT = join(HERE, '../src/widgets/lib_table_descriptions.ts');

/** `(lib (name "X") … (descr "Y"))` rows, as [name, descr]. */
function rows(file) {
  const text = readFileSync(join(TEMPLATE, file), 'utf8');
  const out = [];
  for (const m of text.matchAll(
    /\(lib\s+\(name\s+"((?:[^"\\]|\\.)*)"\)[^\n]*\(descr\s+"((?:[^"\\]|\\.)*)"\)/g,
  )) {
    const unquote = (s) => s.replace(/\\(.)/g, '$1');
    out.push([unquote(m[1]), unquote(m[2])]);
  }
  return out;
}

const sym = rows('sym-lib-table');
const fp = rows('fp-lib-table');

const entries = (list) =>
  list.map(([n, d]) => `  [${JSON.stringify(n)}, ${JSON.stringify(d)}],`).join('\n');

const src = `// SPDX-License-Identifier: GPL-3.0-or-later
// Copyright (C) 2026 ZiroEDA and contributors.
// Portions derived from KiCad, copyright The KiCad Developers. See NOTICE.md.
/**
 * The global library tables' \`(descr …)\` strings, GENERATED by
 * \`designer/scripts/vendor-lib-table-descr.mjs\` from KiCad's own
 * \`template/sym-lib-table\` and \`template/fp-lib-table\`. Do not edit; re-run.
 *
 * This is what the Description column shows against a LIBRARY row in the
 * symbol and footprint choosers: \`row->GetDescr()\` of the library table,
 * which the hosted indexes do not carry. [data]
 */

const SYM: ReadonlyMap<string, string> = new Map([
${entries(sym)}
]);

const FP: ReadonlyMap<string, string> = new Map([
${entries(fp)}
]);

/** \`LIB_TABLE::GetDescription( nickname )\` for the shipped global tables. */
export function symbolLibraryDescription(nickname: string): string {
  return SYM.get(nickname) ?? '';
}

export function footprintLibraryDescription(nickname: string): string {
  return FP.get(nickname) ?? '';
}
`;

writeFileSync(OUT, src);
// The output is checked in and biome-checked like any source; format it the
// way the repo does rather than guessing the formatter's quote style here.
execFileSync('npx', ['biome', 'format', '--write', OUT], {
  cwd: join(HERE, '..'),
  stdio: 'ignore',
});
console.log(`wrote ${OUT}: ${sym.length} symbol libraries, ${fp.length} footprint libraries`);
